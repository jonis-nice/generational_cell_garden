const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync('aesthetic.js','utf8'),ctx);
const a=ctx.window.PLANT_AESTHETICS;
const purple={latin:'Salvia nemorosa',height:.65,flowerColor:'violett/blå',foliageCharacter:'aromatisk låg bladmassa',habit:'upprätt',winterStructure:'medel: upprätta ax kan stå kvar'};
const rose={latin:'Echinacea purpurea',height:1.2,flowerColor:'rosa/lila strålblommor',foliageCharacter:'grov sträv rosett',habit:'upprätt tuva',winterStructure:'hög: mörka konformade fröställningar'};
const grass={latin:'Deschampsia cespitosa',height:.9,flowerColor:'silvergrön',foliageCharacter:'finbladig tuva',habit:'luftig grästuvbildning',winterStructure:'hög: vippor står kvar'};
const yellow={latin:'Rudbeckia fulgida',height:.8,flowerColor:'guldgul',foliageCharacter:'grov bladtextur',habit:'upprätt'};
assert(a.formOf(purple)!==a.formOf(rose),'Different architectures should be identified');
assert(a.pair(purple,rose).score>0,'Complementary pair should score positively');
assert(a.rankAgainstCommunity(grass,[purple,rose]).score>0,'Community score should be positive');
assert(a.colourOf({flowerColor:'guldgul'})==='warm','Warm palette should be classified');
assert(a.colourOf({flowerColor:'violett/blå'})==='cool','Cool palette should be classified');
const neutralGrass={...grass,flowerColor:'silvergrön'};
const balanced=a.rankAgainstCommunity(rose,[purple,neutralGrass]);
const clashing=a.rankAgainstCommunity(yellow,[purple,neutralGrass]);
assert(clashing.colourPenalty>balanced.colourPenalty,'Unbridged warm/cool palettes should receive a stronger penalty');
assert(a.winterOf(rose)>a.winterOf({latin:'x',flowerColor:'vit'}),'Documented winter structure should be rewarded');
console.log('aesthetic composition tests passed');

const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(require('path').join(__dirname, '..', 'compatibility.js'), 'utf8');
const ctx = { window: {} };
vm.runInNewContext(source, ctx);
const evaluate = ctx.window.PLANT_COMPATIBILITY.evaluate;
const sun = { light: 'Sol', height: 0.7, winteringRating: 'A', soilMoisture: 'måttligt fuktig, väldränerad' };
const part = { light: 'Sol–halvskugga', height: 1.1, winteringRating: 'B*', soilMoisture: 'måttligt fuktig' };
const shade = { light: 'Halvskugga–skugga', height: 0.3, winteringRating: null, soilMoisture: 'fuktig' };
const ok = evaluate(sun, part);
const bad = evaluate(sun, shade);
if (bad.status !== 'avoid') throw new Error('Expected clear light mismatch to be avoided');
if (!['candidate','insufficient_data'].includes(ok.status)) throw new Error('Unexpected compatible status');
const dry = {...sun, soilMoisture:'torr till måttligt torr'};
const wet = {...part, soilMoisture:'jämnt fuktig'};
if (evaluate(dry, wet).status !== 'avoid') throw new Error('Expected dry/moist conflict to be screened');
const drained = {...sun, soilMoisture:'måttligt fuktig, väldränerad'};
if (evaluate(drained, part).status === 'avoid') throw new Error('Väldränerad must not be misread as dry');
const ranked = ctx.window.PLANT_COMPATIBILITY.rankAgainstCommunity(part, [sun]);
if (!['candidate','insufficient_data'].includes(ranked.status)) throw new Error('Community ranking failed');
const risky = evaluate({...sun, spreadRisk:'high'}, part);
if (risky.status !== 'avoid') throw new Error('High spread risk must be flagged as conflict');
const mediumRisk = evaluate({...sun, spreadRisk:'medium'}, part);
if (!mediumRisk.reasons.some(x => x.includes('spridningsrisk'))) throw new Error('Medium spread risk must be disclosed');
const unknownWinter = evaluate({...sun, winteringRating:null}, {...part, winteringRating:null});
if (!unknownWinter.reasons.some(x => x.includes('övervintringsbedömning saknas'))) throw new Error('Unknown winter rating must be disclosed');
console.log('compatibility smoke test passed:', ok.status, bad.status, ranked.status);

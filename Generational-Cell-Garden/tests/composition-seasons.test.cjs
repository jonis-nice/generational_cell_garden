const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync('aesthetic.js','utf8'),ctx);
const a=ctx.window.PLANT_AESTHETICS;
const matrix={latin:'Geranium macrorrhizum',height:.35,flowerColor:'rosa',habit:'mattbildande',foliageCharacter:'tät bladmassa',compositionRole:['matrix','groundcover'],springValue:'tidig bladtillväxt',summerValue:'blomning',autumnValue:'röd höstfärg',winterStructure:'vintergrön bladmassa'};
const grass={latin:'Deschampsia cespitosa',height:1,flowerColor:'halmfärgad',habit:'tuvbildande',foliageCharacter:'smala blad och luftiga vippor',compositionRole:['structural_grass','winter_skeleton'],springValue:'bladutveckling',summerValue:'blommande vippor',autumnValue:'halmfärgade vippor',winterStructure:'står kvar över vintern'};
const daisy={latin:'Echinacea purpurea',height:1.1,flowerColor:'rosa',habit:'upprätt tuva',foliageCharacter:'grov bladrosett',compositionRole:['accent','winter_skeleton'],springValue:'bladutveckling',summerValue:'blomning',autumnValue:'fröställningar',winterStructure:'konformade fröställningar'};
assert.strictEqual(a.structuralRole(matrix),'matrix');
assert.strictEqual(a.structuralRole(grass),'structure');
assert.strictEqual(a.structuralRole(daisy),'structure');
const plan=a.communityPlan([matrix,grass,daisy]);
assert.strictEqual(plan.seasons.length,4);
assert.strictEqual(plan.seasonalBalance,1);
assert.ok(plan.counts.matrix===1&&plan.counts.structure===2);
assert.strictEqual(a.seasonalProfile(grass).coverage,1);
assert.ok(a.rolePlacement(matrix,'matrix').length>0);
console.log('composition seasons and roles passed');

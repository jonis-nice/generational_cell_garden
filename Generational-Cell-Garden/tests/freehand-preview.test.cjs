const assert=require('assert'),fs=require('fs'),path=require('path');
const app=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
assert(app.includes("svg.addEventListener('pointerdown'"),'pointerdown starts freehand drawing');
assert(app.includes("svg.addEventListener('pointerup'"),'pointerup completes freehand stroke');
assert(app.includes('svg.setPointerCapture?.(e.pointerId)'),'pointer capture keeps drawing active outside the initial SVG child');
assert(app.includes("svg.addEventListener('pointercancel'"),'cancelled pointer gesture is cleaned up');
assert(app.includes('state.drawPointer.dragging'),'drag gesture is distinguished from click-to-add-vertex');
assert(app.includes('state.suppressClick=true'),'freehand pointerup suppresses synthetic click');
assert(app.includes('function pathPreview(points,close=false)')&&app.includes(' Q ${p[i].x} ${p[i].y} ${mx} ${my}'),'live path preview uses smooth quadratic segments');
assert(app.includes('clean.length>=8?smoothClosed(clean,2)'),'dense freehand stroke is smoothed on completion');
console.log('freehand preview: PASS (drag drawing, click-vertex fallback, smooth live preview and final contour)');
